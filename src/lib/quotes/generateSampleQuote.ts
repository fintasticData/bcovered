// Full SAMPLE motor comparison via fal (Russ). Falls back to fixed demo quotes if fal is off or JSON fails.
import { falApi, FalError } from '@/lib/fal/api'
import { getSampleQuotes } from '@/lib/qe/sampleQuotes'
import type { QeInsurerQuote, QeMotorRequest, QeQuotedItem, QeResult } from '@/lib/qe/types'
import type { QuoteSource } from './sources'

export interface GeneratedSampleQuote {
  source: Extract<QuoteSource, 'sample_fixed' | 'sample_ai'>
  result: QeResult
  model?: string
  cost_usd?: number
  fallback_reason?: string
}

interface AiInsurerRow {
  insurerName: string
  monthlyPremium: number | null
  basicExcess: number | null
  note?: string
}

const SYSTEM = `You are Russ, B-Covered's SAMPLE quote helper for South African personal motor insurance demos.
Return ONLY valid JSON (no markdown) with this shape:
{"insurers":[{"insurerName":"string","monthlyPremium":number|null,"basicExcess":number|null,"note":"string"}]}
Rules:
- Invent 3 fictional insurers suitable for a demo (not real branded prices presented as binding).
- monthlyPremium is ZAR per month; use null for a No Quote.
- basicExcess is ZAR; use null when No Quote.
- Premiums should be plausible for the vehicle year and cover type, but clearly SAMPLE / demo.
- One insurer may return No Quote.
- Keep notes short.`

function localIso(d: Date) {
  const pad = (n: number) => String(n).padStart(2, '0')
  return `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}T${pad(d.getHours())}:${pad(d.getMinutes())}:${pad(d.getSeconds())}`
}

function vehicleItem(quoteItemID: number, quoted: { premium: number; excess: number } | null, note?: string): QeQuotedItem {
  return {
    quoteItemID,
    name: 'Vehicle',
    index: 1,
    premium: quoted?.premium ?? 0,
    statusID: quoted ? 2 : 1,
    status: quoted ? 'Quoted' : 'No Quote',
    breakdown: [],
    valueAddedProducts: [],
    messages: quoted
      ? note
        ? [{ messageTypeID: 1, messageTypeName: 'Details', message: note }]
        : []
      : [{ messageTypeID: 900301, messageTypeName: 'QuoteItem', message: note || 'No quote in this SAMPLE response.' }],
    excess: quoted ? [{ name: 'Basic', description: 'Basic excess', value: quoted.excess }] : [],
  }
}

function toQeResult(rows: AiInsurerRow[], requestID: number, now: Date): QeResult {
  const quoteDate = localIso(now)
  const quoteExpires = localIso(new Date(now.getTime() + 30 * 86_400_000))
  const quotes: QeInsurerQuote[] = rows.slice(0, 3).map((row, i) => {
    const quoted =
      row.monthlyPremium != null && row.basicExcess != null
        ? { premium: Math.round(row.monthlyPremium), excess: Math.round(row.basicExcess) }
        : null
    const item = vehicleItem(i + 1, quoted, row.note)
    const hasQuote = item.status === 'Quoted'
    return {
      status: 'Complete',
      statusID: 3,
      selectedID: 0,
      superseded: false,
      submitDate: '0001-01-01T00:00:00',
      selectedCode: null,
      contactId: '',
      message: '',
      insurerID: 9000 + i,
      insurerParentID: 0,
      insurerName: row.insurerName || `Demo Insurer ${String.fromCharCode(65 + i)}`,
      insurerReference: `AI-SAMPLE-${requestID}-${i + 1}`,
      insurerImage: '',
      validDays: hasQuote ? 30 : 0,
      requestID,
      quoteID: requestID * 10 + i + 1,
      hasExpired: false,
      hasQuote,
      quoteDate: hasQuote ? quoteDate : null,
      quoteExpires: hasQuote ? quoteExpires : null,
      totalPremium: item.premium,
      vapPremium: 0,
      vaP3PPremium: 0,
      items: [item],
      fees: [],
      valueAddedProducts: [],
      messages: [
        {
          messageTypeID: 1,
          messageTypeName: 'Details',
          message: 'SAMPLE · generated by Russ via fal for demonstration only. Not an insurer quotation and cannot be accepted as cover.',
        },
      ],
      history: [],
    }
  })
  while (quotes.length < 3) {
    const i = quotes.length
    quotes.push({
      ...quotes[0],
      insurerID: 9000 + i,
      insurerName: `Demo Insurer ${String.fromCharCode(65 + i)}`,
      insurerReference: `AI-SAMPLE-${requestID}-${i + 1}`,
      quoteID: requestID * 10 + i + 1,
      hasQuote: false,
      totalPremium: 0,
      items: [vehicleItem(i + 1, null, 'Padding No Quote')],
      quoteDate: null,
      quoteExpires: null,
      validDays: 0,
    })
  }
  return {
    requestID,
    status: 'Complete',
    requestStatus: 'Open',
    isComplete: true,
    expectedInsurers: quotes.length,
    completedInsurers: quotes.length,
    elapsedSeconds: 0,
    estimatedSecondsRemaining: null,
    quotes,
  }
}

function parseAiJson(content: string): AiInsurerRow[] | null {
  try {
    const cleaned = content.trim().replace(/^```json\s*/i, '').replace(/```$/i, '').trim()
    const parsed = JSON.parse(cleaned) as { insurers?: AiInsurerRow[] }
    if (!Array.isArray(parsed.insurers) || parsed.insurers.length < 2) return null
    return parsed.insurers
  } catch {
    return null
  }
}

/** Fixed SAMPLE comparison (no network). */
export function generateFixedSampleQuote(request: Readonly<QeMotorRequest>, now = new Date()): GeneratedSampleQuote {
  return { source: 'sample_fixed', result: getSampleQuotes(request, now) }
}

/** SAMPLE comparison via fal LLM; falls back to fixed demo quotes. */
export async function generateAiSampleQuote(request: Readonly<QeMotorRequest>, now = new Date()): Promise<GeneratedSampleQuote> {
  const v = request.vehicles[0]
  const p = request.policyholder
  const user = [
    `Policyholder: ${p.name} ${p.surname}, ${p.address.suburb} ${p.address.postalCode}.`,
    `Vehicle M&M ${v.meadCode}, year ${v.year}, cover code ${v.cover ?? '0'} (0=comprehensive).`,
    'Produce three SAMPLE insurer rows for a private motor demo in South Africa.',
  ].join(' ')

  try {
    const { content, model, usage } = await falApi.chat({
      messages: [
        { role: 'system', content: SYSTEM },
        { role: 'user', content: user },
      ],
      json: true,
      max_tokens: 700,
      temperature: 0.4,
    })
    const rows = parseAiJson(content)
    if (!rows) {
      const fixed = generateFixedSampleQuote(request, now)
      return { ...fixed, fallback_reason: 'Russ returned unusable JSON; showing fixed SAMPLE quotes instead.', model, cost_usd: usage.cost_usd }
    }
    const requestID = Math.floor(now.getTime() / 1000)
    return {
      source: 'sample_ai',
      result: toQeResult(rows, requestID, now),
      model,
      cost_usd: usage.cost_usd,
    }
  } catch (e) {
    const fixed = generateFixedSampleQuote(request, now)
    const reason =
      e instanceof FalError
        ? e.status === 401
          ? 'Sign in to use Russ / fal for AI SAMPLE quotes; showing fixed SAMPLE quotes.'
          : `fal unavailable (${e.message}); showing fixed SAMPLE quotes.`
        : 'AI SAMPLE quote failed; showing fixed SAMPLE quotes.'
    return { ...fixed, fallback_reason: reason }
  }
}
