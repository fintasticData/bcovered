// Writes src/lib/supabase/columns.generated.ts: every public table's columns, and which tables carry the Sample / Live
// category. The browser sync adapter only sends columns the database has.
//   node scripts/gen-supabase-columns.mjs
// Uses SUPABASE_DB_URL (pg) when it is a valid connection string; otherwise the seed-loader Edge Function
// (SEED_LOADER_URL / SEED_LOADER_SECRET or node_modules/.cache/seed-secret.txt).
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SQL = `select coalesce(json_object_agg(table_name, cols order by table_name), '{}'::json) as columns
  from (select c.table_name, json_agg(c.column_name order by c.ordinal_position) as cols
          from information_schema.columns c
          join information_schema.tables t on t.table_schema = c.table_schema and t.table_name = c.table_name and t.table_type = 'BASE TABLE'
         where c.table_schema = 'public'
         group by c.table_name) s`

function envValue(name) {
  if (process.env[name]) return process.env[name]
  for (const file of ['.env.local', '.env']) {
    const p = resolve(root, file)
    if (!existsSync(p)) continue
    const line = readFileSync(p, 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`))
    if (line) return line.slice(name.length + 1).trim()
  }
  return null
}

async function viaPg(url) {
  const { default: pg } = await import('pg')
  const client = new pg.Client({ connectionString: url, ssl: { rejectUnauthorized: false } })
  await client.connect()
  try {
    return (await client.query(SQL)).rows[0].columns
  } finally {
    await client.end()
  }
}

async function viaLoader() {
  const url = process.env.SEED_LOADER_URL ?? 'https://cgwgmzpcrvimoqaxgoop.supabase.co/functions/v1/seed-loader'
  const secretFile = resolve(root, 'node_modules/.cache/seed-secret.txt')
  const secret = process.env.SEED_LOADER_SECRET ?? (existsSync(secretFile) ? readFileSync(secretFile, 'utf8').trim() : '')
  const res = await fetch(url, { method: 'POST', headers: { 'Content-Type': 'application/json', 'x-seed-secret': secret }, body: JSON.stringify({ action: 'sql', sql: SQL }) })
  const json = await res.json()
  if (!json.ok) throw new Error(JSON.stringify(json))
  return json.result[0].columns
}

const dbUrl = envValue('SUPABASE_DB_URL')
let validUrl = false
try {
  validUrl = Boolean(dbUrl && new URL(dbUrl).hostname && !dbUrl.includes('<'))
} catch {
  validUrl = false
}
const columns = validUrl ? await viaPg(dbUrl) : await viaLoader()
const categoryTables = Object.entries(columns).filter(([, cols]) => cols.includes('data_category')).map(([t]) => t)

const body = [
  '// Generated by scripts/gen-supabase-columns.mjs from the bcovered database. Do not edit by hand.',
  `export const SUPABASE_COLUMNS: Record<string, readonly string[]> = ${JSON.stringify(columns, null, 0).replace(/\],"/g, '],\n  "').replace(/^\{/, '{\n  ').replace(/\}$/, ',\n}')}`,
  '',
  `/** Tables whose rows carry the Sample / Live category. */`,
  `export const CATEGORY_TABLES: readonly string[] = ${JSON.stringify(categoryTables)}`,
  '',
].join('\n')
writeFileSync(resolve(root, 'src/lib/supabase/columns.generated.ts'), body)
console.log(`Wrote ${Object.keys(columns).length} tables (${categoryTables.length} with a category).`)
